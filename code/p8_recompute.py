#!/usr/bin/env python3
"""P8 revision -- single-source recomputation of every number in the paper.

One resampling scheme, applied to all twelve conventions, the metric axis and
the matching-geometry axis:

  * QC filter straight from S1 (absolute |dt| <= 1200 s, dcell <= 20 km,
    m35_det == 1).  m35_det is 1 for every row, so the third condition is
    documented as inert.
  * Surface classes use ONE rule everywhere (defect: si=255 was counted as
    ice in the cell/area pooling of the submitted version but excluded from
    the profile pooling).  Here ice = (si >= 50) & (si != 255); water = si == 0.
  * Bootstrap unit is the CALIPSO granule (cal_file); July has 31 granules.
    2,000 replicates, seed 20261110, percentile intervals.  The same
    resampling is used for every score, so X and 1-recall sit on one footing.
  * Cell pooling: 0.5 deg cells, a cell assigned to a class only when >= 90 %
    of its (>=5) profiles belong to that class; counts are aggregated over the
    whole assigned cell.  Area pooling: the same aggregation with each cell
    weighted by cos(latitude).

Outputs: numbers.json (superset consumed by make_figures.py and the table
generators), and CSVs in code/csv/.  Tables are regenerated by tabgen.py.
"""
from __future__ import annotations

import argparse
import json
import os

import numpy as np
import pandas as pd

NBOOT = int(os.environ.get("P8_NBOOT", "2000"))
SEED = 20261110
DT_MAX = 1200.0
DCELL_MAX = 20.0

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
CSV_DIR = os.path.join(HERE, "csv")
os.makedirs(CSV_DIR, exist_ok=True)


# --------------------------------------------------------------------------- IO
def load(path: str) -> pd.DataFrame:
    d = pd.read_csv(path)
    d["month"] = pd.to_datetime(d["time"]).dt.month
    d = d[(d.dt_sec.abs() <= DT_MAX) & (d.dcell_km <= DCELL_MAX)].copy()
    return d


def surfaces(df: pd.DataFrame) -> None:
    """Attach ice/water masks with ONE documented rule (si=255 excluded)."""
    df["ice"] = (df.si >= 50) & (df.si != 255)
    df["water"] = df.si == 0


# ------------------------------------------------------------------- pooling
def _cell_masks(df: pd.DataFrame):
    df = df.copy()
    df["clat"] = np.floor(df.lat / 0.5) * 0.5 + 0.25
    df["clon"] = np.floor(df.lon / 0.5) * 0.5 + 0.25
    df["cell"] = df.clat.astype(str) + "," + df.clon.astype(str)
    g = df.groupby("cell")
    n = g.size()
    ice_f = g["ice"].sum() / n
    wat_f = g["water"].sum() / n
    ice_cells = ice_f.index[(ice_f >= 0.90) & (n >= 5)]
    wat_cells = wat_f.index[(wat_f >= 0.90) & (n >= 5)]
    ice_mask = df.cell.isin(ice_cells)
    wat_mask = df.cell.isin(wat_cells)
    df["w_ice"] = np.where(ice_mask, np.cos(np.deg2rad(df.clat)), 0.0)
    df["w_wat"] = np.where(wat_mask, np.cos(np.deg2rad(df.clat)), 0.0)
    return df, ice_mask, wat_mask


def _stats(df, truth, level, ice_mask, water_mask, wice=None, wwat=None):
    clear = df.m35_lvl >= level
    c = clear.to_numpy()
    t = df[truth].to_numpy()
    out = {}
    for cls, m in (("ice", ice_mask), ("water", water_mask)):
        mc = c[m.to_numpy()] if hasattr(m, "to_numpy") else c[m]
        mt = t[m.to_numpy()] if hasattr(m, "to_numpy") else t[m]
        w = None
        if cls == "ice" and wice is not None:
            w = wice[m].to_numpy()
        if cls == "water" and wwat is not None:
            w = wwat[m].to_numpy()
        if w is not None:
            wr = float(np.sum(w * (mc & mt)))
            den = float(np.sum(w * mc))
        else:
            wr = int((mc & mt).sum()); den = int(mc.sum())
        ncloud = int(mt.sum())
        X = wr / den if den else np.nan
        omr = wr / ncloud if ncloud else np.nan
        out[cls] = dict(X=X, omr=omr, nc=int(den), ncloud=ncloud, wr=int(wr) if w is None else None)
    return out


def profile_rate(df, truth, level):
    return _stats(df, truth, level, df.ice, df.water)


def cell_rate(df, truth, level):
    df, ice_mask, wat_mask = _cell_masks(df)
    return _stats(df, truth, level, ice_mask, wat_mask)


def area_rate(df, truth, level):
    df, ice_mask, wat_mask = _cell_masks(df)
    return _stats(df, truth, level, ice_mask, wat_mask,
                  wice=df["w_ice"], wwat=df["w_wat"])


POOL = {"prof": profile_rate, "cell": cell_rate, "area": area_rate}


def rate(df, truth, level, pool):
    return POOL[pool](df, truth, level)


# ---------------------------------------------------------------- bootstrap
def bootstrap_ratio(jul, stat_fn, rng, ndraw=NBOOT):
    groups = [g for _, g in jul.groupby("cal_file")]
    ng = len(groups)
    draws = np.empty(ndraw)
    for b in range(ndraw):
        pick = rng.integers(0, ng, ng)
        sample = pd.concat([groups[i] for i in pick], ignore_index=True)
        try:
            draws[b] = stat_fn(sample)
        except (ZeroDivisionError, ValueError):
            draws[b] = np.nan
    draws = draws[~np.isnan(draws)]
    if len(draws) == 0:
        return [np.nan, np.nan], []
    lo, hi = np.nanpercentile(draws, [2.5, 97.5])
    return [float(lo), float(hi)], draws.tolist()


def ratio_stat(pool, truth, level, which="X"):
    def f(df):
        r = rate(df, truth, level, pool)
        return r["ice"][which] / r["water"][which]
    return f


# --------------------------------------------------------------- main driver
def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", default=os.path.join(ROOT, "supp", "S1_matchups.csv"))
    ap.add_argument("--out", default=os.path.join(ROOT, "numbers.json"))
    args = ap.parse_args()

    raw = pd.read_csv(args.csv)
    d = load(args.csv)
    surfaces(d)
    jul = d[d.month == 7].reset_index(drop=True)
    apr = d[d.month == 4].reset_index(drop=True)

    print(f"QC: {len(d)} rows, {d.cal_file.nunique()} granules "
          f"(July {len(jul)}/{jul.cal_file.nunique()}, "
          f"April {len(apr)}/{apr.cal_file.nunique()}); m35_det unique={d.m35_det.unique()}")

    # ---------- twelve conventions (point + ratio CI) ----------
    conventions = []
    for truth, tname in (("cal_thick", "thick"), ("cal_cloud", "any")):
        for level, lname in ((2, "clear_incl"), (3, "clear_conf")):
            for pool, pname in (("prof", "prof"), ("cell", "cell"), ("area", "area")):
                r = rate(jul, truth, level, pool)
                ratio = r["ice"]["X"] / r["water"]["X"]
                ci, dist = bootstrap_ratio(jul, ratio_stat(pool, truth, level, "X"),
                                            np.random.default_rng(SEED))
                row = dict(truth=tname, clear=lname, pool=pool,
                           ice=r["ice"]["X"], water=r["water"]["X"],
                           ratio=ratio, ice_lo=np.nan, ice_hi=np.nan,
                           water_lo=np.nan, water_hi=np.nan,
                           ratio_lo=ci[0], ratio_hi=ci[1],
                           ratio_med=float(np.median(dist)) if dist else np.nan,
                           ice_fn=r["ice"]["wr"])
                conventions.append(row)
                print(f"  {tname:5s} {lname:10s} {pname:5s} "
                      f"X={r['ice']['X']:.3f}/{r['water']['X']:.3f} "
                      f"ratio={ratio:.3f} CI[{ci[0]:.2f},{ci[1]:.2f}] "
                      f"ice_fn={r['ice']['wr']}/{r['ice']['nc']} waterX={r['water']['X']:.3f}")
    # ice/water intervals only needed for the 4 profile rows (fig2)
    for truth, tname in (("cal_thick", "thick"), ("cal_cloud", "any")):
        for level, lname in ((2, "clear_incl"), (3, "clear_conf")):
            ci_ice, _ = bootstrap_ratio(jul,
                lambda df, t=truth, l=level: profile_rate(df, t, l)["ice"]["X"],
                np.random.default_rng(SEED))
            ci_wat, _ = bootstrap_ratio(jul,
                lambda df, t=truth, l=level: profile_rate(df, t, l)["water"]["X"],
                np.random.default_rng(SEED))
            for row in conventions:
                if row["truth"] == tname and row["clear"] == lname and row["pool"] == "prof":
                    row["ice_lo"], row["ice_hi"] = ci_ice
                    row["water_lo"], row["water_hi"] = ci_wat
    conv_df = pd.DataFrame(conventions)
    conv_df.to_csv(os.path.join(CSV_DIR, "conventions_july.csv"), index=False)

    # ---------- metric axis (1 - recall), profile pooling ----------
    metric = {}
    for truth, tname in (("cal_thick", "thick"), ("cal_cloud", "any")):
        m = {}
        for level, lname in ((2, "clear_incl"), (3, "clear_conf")):
            r = profile_rate(jul, truth, level)
            ratio = r["ice"]["X"] / r["water"]["X"]
            xci, _ = bootstrap_ratio(jul, ratio_stat("prof", truth, level, "X"),
                                     np.random.default_rng(SEED))
            omrci, _ = bootstrap_ratio(jul, ratio_stat("prof", truth, level, "omr"),
                                       np.random.default_rng(SEED))
            m[lname] = dict(
                X_ice=r["ice"]["X"], X_water=r["water"]["X"], X_ratio=ratio, X_ci=xci,
                omr_ice=r["ice"]["omr"], omr_water=r["water"]["omr"],
                omr_ratio=r["ice"]["omr"] / r["water"]["omr"], omr_ci=omrci)
            print(f"  metric {tname} {lname}: X_ratio={ratio:.3f} "
                  f"omr_ratio={m[lname]['omr_ratio']:.3f} omr_ci={omrci}")
        metric[tname] = m
    pd.DataFrame([{"truth": t, "clear": c, **v} for t, mm in metric.items()
                  for c, v in mm.items()]).to_csv(
        os.path.join(CSV_DIR, "metric_axis.csv"), index=False)

    # ---------- paired change (thick -> any), signed bootstrap ----------
    change_rng = np.random.default_rng(SEED)
    groups = [g for _, g in jul.groupby("cal_file")]
    ng = len(groups)
    dw, di = [], []
    for _ in range(NBOOT):
        pick = change_rng.integers(0, ng, ng)
        s = pd.concat([groups[i] for i in pick], ignore_index=True)
        clear = s.m35_lvl >= 2
        ice = (s.si >= 50) & (s.si != 255); water = s.si == 0
        def Xv(mask):
            c = clear[mask].to_numpy(); t = s["cal_thick"][mask].to_numpy()
            return int((c & t).sum()) / int(c.sum()) if int(c.sum()) else np.nan
        def Xa(mask):
            c = clear[mask].to_numpy(); t = s["cal_cloud"][mask].to_numpy()
            return int((c & t).sum()) / int(c.sum()) if int(c.sum()) else np.nan
        dw.append(Xa(water) - Xv(water)); di.append(Xa(ice) - Xv(ice))
    dw = np.array(dw); di = np.array(di)
    paired = dict(
        water=dict(point=float(dw.mean()), lo=float(np.nanpercentile(dw, 2.5)),
                   hi=float(np.nanpercentile(dw, 97.5))),
        ice=dict(point=float(di.mean()), lo=float(np.nanpercentile(di, 2.5)),
                 hi=float(np.nanpercentile(di, 97.5))))
    print("  paired change water", paired["water"], "ice", paired["ice"])

    # ---------- matching geometry (5th axis) ----------
    bands = (("<=300 s", jul.dt_sec.abs() <= 300),
             ("300-900 s", (jul.dt_sec.abs() > 300) & (jul.dt_sec.abs() <= 900)),
             (">900 s", jul.dt_sec.abs() > 900))
    geo = []
    for name, mask in bands:
        sub = jul[mask].reset_index(drop=True)
        r = profile_rate(sub, "cal_thick", 2)
        ratio = r["ice"]["X"] / r["water"]["X"]
        ci, _ = bootstrap_ratio(sub, ratio_stat("prof", "cal_thick", 2, "X"),
                                np.random.default_rng(SEED))
        geo.append(dict(band=name, n=int(len(sub)),
                        ice_X=r["ice"]["X"], water_X=r["water"]["X"],
                        ratio=ratio, ci=ci))
        print(f"  geo {name}: n={len(sub)} ratio={ratio:.3f} CI{ci}")
    dt_median = float(jul.dt_sec.abs().median())
    dt_frac = float((jul.dt_sec.abs() > 600).mean())
    pd.DataFrame(geo).to_csv(os.path.join(CSV_DIR, "geometry.csv"), index=False)

    # ---------- branch-1 within-branch ratio (proper interval) ----------
    b1 = jul[(jul.m35_snowpath == 1)].reset_index(drop=True)
    brng = np.random.default_rng(SEED)
    draws = []
    for _ in range(NBOOT):
        s = b1.iloc[brng.integers(0, len(b1), len(b1))].reset_index(drop=True)
        xi = profile_rate(s, "cal_thick", 2)["ice"]["X"]
        xw = profile_rate(s, "cal_thick", 2)["water"]["X"]
        draws.append(xi / xw)
    draws = np.array([x for x in draws if x == x])
    branch1_ratio = float(np.nanmedian(draws))
    branch1_ci = [float(np.nanpercentile(draws, 2.5)),
                  float(np.nanpercentile(draws, 97.5))]
    print(f"  branch-1 ratio={branch1_ratio:.3f} CI{branch1_ci}")

    # ---------- assemble numbers.json (superset) ----------
    prev = json.load(open(args.out, encoding="utf-8")) if os.path.exists(args.out) else {}
    out = dict(prev)  # keep branch/axis/lit/branch_x/water_gap blocks
    out["qc"] = dict(n_raw=len(raw), n_rows=len(d), n_granules=int(d.cal_file.nunique()),
                     n_jul=int(len(jul)), n_jul_granules=int(jul.cal_file.nunique()),
                     n_apr=int(len(apr)), n_apr_granules=int(apr.cal_file.nunique()),
                     dt_max=DT_MAX, dcell_max=DCELL_MAX,
                     m35_det_unique=[int(x) for x in d.m35_det.unique().tolist()])
    out["bootstrap"] = dict(unit="cal_file (July granules, n=31)",
                            nboot=NBOOT, seed=SEED, type="percentile",
                            pooling="profile, cell, area")
    out["table1"] = [dict(truth=r["truth"], clear=r["clear"], pool=r["pool"],
                          ice=r["ice"], water=r["water"], ratio=r["ratio"],
                          ice_lo=r["ice_lo"], ice_hi=r["ice_hi"],
                          water_lo=r["water_lo"], water_hi=r["water_hi"],
                          ratio_lo=r["ratio_lo"], ratio_hi=r["ratio_hi"],
                          ratio_med=r["ratio_med"], ice_fn=r["ice_fn"])
                     for r in conventions]
    out["n_conventions"] = len(conventions)
    out["ratio_min"] = float(conv_df.ratio.min())
    out["ratio_max"] = float(conv_df.ratio.max())
    out["ratio_span_factor"] = float(conv_df.ratio.max() / conv_df.ratio.min())
    cross = conv_df[(conv_df.ratio_lo < 1) & (conv_df.ratio_hi > 1)]
    out["n_ratio_ci_including_unity"] = int(len(cross))
    out["ratio_rows_crossing_unity"] = cross[["truth", "clear", "pool", "ratio",
                                              "ratio_lo", "ratio_hi"]].to_dict("records")
    out["metric_axis_v2"] = metric
    out["paired_change_v2"] = paired
    out["matching_geometry"] = geo
    out["dt_median"] = dt_median
    out["dt_frac_over_600"] = dt_frac
    out["branch1_ratio"] = dict(ratio=branch1_ratio, ci=branch1_ci)
    out["si255_rule"] = "excluded from both ice and water strata (one rule for all poolings)"

    with open(args.out, "w", encoding="utf-8") as fh:
        json.dump(out, fh, indent=1, ensure_ascii=False)
    print(f"wrote {os.path.abspath(args.out)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
